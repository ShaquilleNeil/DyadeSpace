// Path URLs on web (public /privacy route) — see
// lib/utils/url_strategy_web.dart. dart.library.js_interop
// is true on both web renderers (JS and WASM) and false on
// mobile, so the stub is used everywhere else.
import 'utils/url_strategy.dart'
    if (dart.library.js_interop) 'utils/url_strategy_web.dart';
// firebase_options.dart is generated by `flutterfire configure`
// during setup (see SETUP_CHECKLIST.md) - it is git-ignored.
import 'firebase_options.dart';

/// FCM background handler. Must be a top-level function in the
/// root library and annotated as an entry point so it survives
/// tree-shaking in release builds. DyadeSpace only receives
/// notification messages (title/body rendered by the OS itself),
/// so there is no data payload to process here - the handler
/// exists because the messaging SDK requires one to be
/// registered for background/terminated delivery.
@pragma('vm:entry-point')
Future<void> _firebaseMessagingBackgroundHandler(
    RemoteMessage message) async {
  // Nothing to do: no UI, no state - see the comment above.
}

Future<void> main() async {
  // Web only (no-op elsewhere): read the browser's pathname as
  // the route, before anything else boots. Without this the
  // engine uses hash routing and a direct /privacy URL starts
  // the app at '/' instead.
  configureUrlStrategy();
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );
  // Crashlytics: framework errors and uncaught async errors
  // land in the console instead of only in `flutter run` output.
  FlutterError.onError = (details) => FirebaseCrashlytics.instance
      .recordFlutterError(details, fatal: false);
  PlatformDispatcher.instance.onError = (error, stack) {
    FirebaseCrashlytics.instance.recordError(error, stack, fatal: true);
    return true;
  };
  // App Check, mobile release builds only. Play Integrity fails
  // on debug builds (they are not release-signed), so activating
  // unconditionally would break the owner's `flutter run`
  // testing — debug builds skip App Check. Web is not activated
  // here: it needs a reCAPTCHA v3 site key from the Firebase
  // console first (a console step, see the audit report).
  // Enforcement is NOT turned on in code — it is a console
  // toggle, also listed in the report.
  if (!kIsWeb && kReleaseMode) {
    await FirebaseAppCheck.instance.activate(
      providerAndroid: const AndroidPlayIntegrityProvider(),
      providerApple: const AppleAppAttestProvider(),
    );
  }
  // Background push delivery is mobile-only: the web control
  // center does not subscribe to push, and registering a
  // background handler is not supported on web.
  if (!kIsWeb) {
    FirebaseMessaging.onBackgroundMessage(
        _firebaseMessagingBackgroundHandler);
    // Auto clock-in's ~15-minute background check (Workmanager).
    // Registering the dispatcher does not start any work: the
    // periodic task is only registered when the worker turns
    // auto clock-in on in Settings.
    await Workmanager().initialize(
      autoClockCallbackDispatcher,
    );
  }
  // Load the saved theme choice before the first frame so the
  // app opens in the right theme (dark default). If the
  // persisted prefs cannot be read at all (corrupt store,
  // platform error), fall back to defaults and keep starting
  // instead of failing startup — a broken prefs read must
  // never brick the app.
  ThemeMode themeMode;
  try {
    themeMode = await loadThemeMode();
  } catch (e) {
    debugPrint('Could not load saved theme, using dark default: $e');
    themeMode = ThemeMode.dark;
  }
  // Same for language: a saved choice wins, otherwise the
  // phone's language ('fr' for any French variant).
  String language;
  try {
    language = await loadLanguage();
  } catch (e) {
    debugPrint('Could not load saved language, using device language: $e');
    final code = PlatformDispatcher.instance.locale.languageCode;
    language = (code == 'fr' || code == 'es') ? code : 'en';
  }
  runApp(ProviderScope(
    overrides: [
      themeModeProvider.overrideWith((ref) => themeMode),
      localeProvider.overrideWith((ref) => language),
    ],
    child: const DyadeSpaceApp(),
  ));
}
